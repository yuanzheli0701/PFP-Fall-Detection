("h1", "Ⅳ. 度量学习"),
("h2", "Ⅳ.1 原理"),
("p", "度量学习训练一个神经网络 f，把每个输入 x 映射为嵌入向量 f(x)，通常维度较低并归一化为单位长度。训练目标是让两个嵌入之间的距离反映输入的相似程度：两个跌倒样本应当靠近，跌倒窗口与行走窗口应当远离。网络不被要求直接输出类别；分类在之后通过比较嵌入空间中的距离完成。"),
("p", "这改变了数据的使用方式：监督分类器从单个带标签样本学习，而度量学习模型从样本对（pair）或三元组（triplet）学习。N 个样本可组成约 N²/2 量级的样本对，因此小数据集仍能提供大量训练信号。这也是度量学习被广泛用于小样本学习（few-shot learning）的原因（Koch et al., 2015; Snell et al., 2017）。"),
("h2", "Ⅳ.2 孪生网络与对比损失"),
("p", "孪生网络（siamese network）由两个完全相同、共享权重的分支组成（Chicco, 2021）。每个分支接收一对输入中的一个并输出其嵌入。由于权重共享，两个输入被投影到同一空间，然后计算两个嵌入之间的距离 d。对比损失（Hadsell et al., 2006）在带标签样本对上训练网络："),
("formula", "L = y·d² + (1 − y)·max(0, m − d)²"),
("p", "其中 y = 1 表示两个输入属于同类，y = 0 表示不同类；m 是间隔（margin）。相似样本对被拉近，不相似样本对被推远，直到距离超过 m；已经相距足够远的样本对不再产生贡献。Koch 等人（2015）表明孪生网络能从单个示例识别新类别，这使其成为小样本问题的参考方法。"),
("note", "译注：公式逐项含义、数值例子与「注意 y 的定义方向」见【附录A·公式1】。"),
("h2", "Ⅳ.3 三元组网络与三元组损失"),
("p", "三元组损失由 FaceNet（Schroff et al., 2015）推广，一次处理三个样本：锚点 a、同类正样本 p、异类负样本 n。它要求锚点到正样本的距离比到负样本至少近一个间隔 α："),
("formula", "L = max(0, ‖f(a) − f(p)‖² − ‖f(a) − f(n)‖² + α)"),
("p", "对比损失约束的是绝对距离，而三元组损失只约束相对距离：这给嵌入空间更大的自由度，通常带来更好的表示。主要难点在于三元组的选择——大多数随机三元组「太容易」：已满足间隔、不产生梯度。因此 FaceNet 选择「半困难（semi-hard）」负样本：比正样本远，但仍落在间隔之内。Hermans 等人（2017）提出「批次内最难（batch-hard）」挖掘：在每个批次中取最难的正样本和负样本；他们还建议构建 P 个类别、每类 K 个样本的批次，保证每个批次中每个类别都有代表。这种平衡采样对跌倒检测这类不平衡问题尤为重要。"),
("note", "译注：公式的三段式理解（合格→0、不合格→拉近正样本/推远负样本）、数值例子与挖掘策略，见【附录A·公式2】。"),
