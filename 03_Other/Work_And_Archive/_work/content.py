("h3", "Ⅳ.4.a 最近邻分类（k-NN）"),
("p", "k-NN 分类器找出距查询样本最近的 k 个参考嵌入，并赋予其中占多数的类别。它无需额外训练，且能自然处理复杂的类形状。但它对噪声样本和类别不平衡敏感：当非跌倒远多于跌倒时，一个模棱两可窗口的最近邻更可能是非跌倒；其推理成本也随存储的参考样本数增长。"),
("h3", "Ⅳ.4.b 基于原型的分类"),
("p", "原型网络（Snell et al., 2017）用单个原型 c_k 表示每个类别 k，即该类参考样本 S_k 的嵌入均值："),
("formula", "c_k = (1/|S_k|) · Σ_{x_i ∈ S_k} f(x_i)"),
